-- Weekly session counts for 2026 before the app, from the Abrechnung workbook (sheets B01 to B40,
-- "SESSIONS TOTAL" per week split by coach, and the "ANALYSE" column). Used by the Stats page for
-- weeks 1 to 40; from week 41 (5 Oct) the sessions logged in the app are counted instead.
-- Written without any removing statements so it can be applied directly.

create table if not exists public.stats_history (
  week_start  date not null,
  iso_week    int  not null,
  coach_name  text,             -- null on the analyses row
  sessions    numeric(6,2) not null default 0,
  analyses    numeric(6,2) not null default 0,
  source      text not null default 'Abrechnung 2026'
);
create unique index if not exists stats_history_once on public.stats_history (week_start, coalesce(coach_name, ''));
alter table public.stats_history enable row level security;
create policy stats_history_read on public.stats_history for select to authenticated using (public.is_admin());
revoke all on public.stats_history from anon, authenticated;
grant select on public.stats_history to authenticated;

